/** Translates the policy to database table and column names. */
export function resolvePolicy(definition: AnalyticsCopyPolicyDefinition = analyticsCopyPolicy): AnalyticsCopyPolicy {
  const tables: Record<TableName, PgTable> = schema;
  const resolved: AnalyticsCopyPolicy = {};
  for (const [key, labels] of Object.entries(definition) as [TableName, Record<string, ColumnLabel>][]) {
    const table = tables[key];
    const columns = getTableColumns(table);
    resolved[getTableName(table)] = Object.fromEntries(
      Object.entries(labels).map(([property, label]) => [columns[property].name, label]),
    );
  }
  return resolved;
}

/** The database columns to copy for each database table. Tables with nothing to copy are left out. */
export function copiedColumns(policy: AnalyticsCopyPolicy = resolvePolicy()): Map<string, string[]> {
  const result = new Map<string, string[]>();
  for (const [table, columns] of Object.entries(policy)) {
    const copied = Object.entries(columns)
      .filter(([, label]) => label === 'copy')
      .map(([column]) => column);
    if (copied.length > 0) {
      result.set(table, copied);
    }
  }
  return result;
}
