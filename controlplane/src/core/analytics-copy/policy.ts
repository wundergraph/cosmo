/**
 * Which columns of the controlplane database may be copied into the analytics database.
 *
 * Every column of every table in `src/db/schema.ts` must have a label here, keyed by the same names as in
 * the schema. The type below makes a missing or misspelled table or column a TypeScript error, so a new column
 * is never copied until someone decides it is safe. Only columns labelled `copy` leave the source database.
 * All other labels say why a column stays:
 *
 * - `copy`    — safe to copy: IDs (including user IDs, so joins work), flags, enums, counts, timestamps,
 *               hashes and Stripe IDs.
 * - `pii`     — identifies a person: emails, names derived from emails, git authors, GitHub and Slack identities.
 * - `secret`  — credentials and signing material: tokens, keys, webhook secrets, auth headers.
 * - `content` — what customers wrote or named: schemas, operations, names, labels, URLs and free-text messages.
 *               It can contain personal data and is confidential to the customer.
 */
export type ColumnLabel = 'copy' | 'pii' | 'secret' | 'content';

type Schema = typeof schema;
type TableName = { [K in keyof Schema]: Schema[K] extends PgTable ? K : never }[keyof Schema];

/** One label for every column of every table in the schema, nothing more and nothing less. */
export type AnalyticsCopyPolicyDefinition = {
  [K in TableName]: Schema[K] extends PgTable<infer T extends TableConfig>
    ? { [C in keyof T['columns']]: ColumnLabel }
    : never;
};

