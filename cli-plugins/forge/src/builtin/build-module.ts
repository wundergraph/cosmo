import { routerModule } from './resolve.js';

export const buildModuleName = 'forge.local/build';

export interface BuildModule {
  goVersion: string;
  routerVersion: string;
  /** A router checkout to build from instead of the pinned version, for router development. */
  routerReplace?: string;
  remoteModules: { module: string; package: string; version: string }[];
  /** `directory` is relative to the build module or absolute. */
  localModules: { module: string; directory: string }[];
}

const localModuleVersion = 'v0.0.0';

export const renderGoMod = (build: BuildModule): string => {
  const requirements = new Map<string, string>([[routerModule, build.routerVersion]]);
  for (const module of build.remoteModules) {
    requirements.set(module.module, module.version);
  }
  for (const module of build.localModules) {
    requirements.set(module.module, localModuleVersion);
  }

  const replacements = build.localModules.map((module) => `replace ${module.module} => ${module.directory}`);
  if (build.routerReplace !== undefined) {
    replacements.unshift(`replace ${routerModule} => ${build.routerReplace}`);
  }

  const lines = [
    `module ${buildModuleName}`,
    '',
    `go ${build.goVersion}`,
    '',
    'require (',
    ...[...requirements].map(([module, version]) => `\t${module} ${version}`),
    ')',
  ];
  if (replacements.length > 0) {
    lines.push('', ...replacements);
  }
  return `${lines.join('\n')}\n`;
};

export const renderMainGo = (build: BuildModule): string => {
  const packages = [
    ...build.remoteModules.map((module) => module.package),
    ...build.localModules.map((module) => module.module),
  ];
  const lines = [
    '// Code generated by wgc forge. DO NOT EDIT.',
    '',
    'package main',
    '',
    'import (',
    `\troutercmd "${routerModule}/cmd"`,
  ];
  if (packages.length > 0) {
    lines.push('', ...packages.map((packagePath) => `\t_ "${packagePath}"`));
  }
  lines.push(')', '', 'func main() {', '\troutercmd.Main()', '}');
  return `${lines.join('\n')}\n`;
};
