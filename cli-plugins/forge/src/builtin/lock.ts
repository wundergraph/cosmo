import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import type { Result } from '@wundergraph/wgc-plugin-sdk';
import yaml from 'js-yaml';
import { z } from 'zod';
import { fail } from './failure.js';
import { describeSchemaIssue, remoteModuleSourceSchema, routerSourceSchema } from './manifest.js';

export const lockFileName = 'forge.lock';

const fullCommit = z.string().regex(/^[\da-f]{40}$/, { error: 'must be a full 40 character commit SHA' });

export const lockedRouterSchema = z.strictObject({
  source: routerSourceSchema,
  commit: fullCommit,
  /** The Go module version of github.com/wundergraph/cosmo/router at that commit. */
  version: z.string().min(1),
  goVersion: z.string().min(1),
});

export const lockedModuleSchema = z.strictObject({
  source: remoteModuleSourceSchema,
  /** The Go module that contains the package. */
  module: z.string().min(1),
  /** The Go package the router imports. */
  package: z.string().min(1),
  version: z.string().min(1),
  commit: fullCommit.optional(),
});

export const lockSchema = z.strictObject({
  version: z.literal(1),
  router: lockedRouterSchema,
  modules: z.array(lockedModuleSchema).default([]),
});

export type LockedRouter = z.infer<typeof lockedRouterSchema>;
export type LockedModule = z.infer<typeof lockedModuleSchema>;
export type Lock = z.infer<typeof lockSchema>;

const header = '# Generated by `wgc forge`. Do not edit; run `wgc forge lock` after editing forge.yaml.\n';

export const parseLock = (text: string): Result<Lock> => {
  let document: unknown;
  try {
    document = yaml.load(text);
  } catch (error) {
    return fail({
      message: `${lockFileName} is not valid YAML: ${error instanceof Error ? error.message : String(error)}`,
      input: lockFileName,
      fix: `Delete ${lockFileName} and run \`wgc forge lock\` to write it again.`,
    });
  }

  const parsed = lockSchema.safeParse(document);
  if (!parsed.success) {
    return fail({
      ...describeSchemaIssue(lockFileName, parsed.error),
      fix: `Delete ${lockFileName} and run \`wgc forge lock\` to write it again.`,
    });
  }
  return { success: true, data: parsed.data };
};

/** Reads forge.lock. A workspace that has never been locked has none, which is not an error. */
export const readLock = async (workspace: string): Promise<Result<Lock | undefined>> => {
  let text: string;
  try {
    text = await readFile(path.join(workspace, lockFileName), 'utf8');
  } catch {
    return { success: true, data: undefined };
  }
  return parseLock(text);
};

export const renderLock = (lock: Lock): string => `${header}${yaml.dump(lock, { lineWidth: -1 })}`;

export const writeLock = async (workspace: string, lock: Lock): Promise<void> => {
  await writeFile(path.join(workspace, lockFileName), renderLock(lock));
};
