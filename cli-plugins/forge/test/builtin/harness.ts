export const routerModule = 'github.com/wundergraph/cosmo/router';

export const commitA = 'a'.repeat(40);
export const commitB = 'b'.repeat(40);
export const versionA = 'v0.0.0-20260101000000-aaaaaaaaaaaa';
export const versionB = 'v0.0.0-20260101000000-bbbbbbbbbbbb';

export const lockForReleaseA = `# Generated by \`wgc forge\`. Do not edit; run \`wgc forge lock\` to refresh the pins.
version: 1
router:
  source:
    release: 0.299.0
  commit: ${commitA}
  version: ${versionA}
  goVersion: 1.26.0
modules: []
`;

export interface FakeSystemOptions {
  /** Router tags in the Cosmo repository: version to commit. */
  routerTags?: Record<string, string>;
  /** Answers of `go list -m -json <query>` for modules other than the router. */
  modules?: Record<string, { Path: string; Version: string; Hash?: string }>;
  /** Answers of `git ls-remote <url> ...` for module repositories, as raw output. */
  remotes?: Record<string, string>;
  compileError?: string;
  /** Output of `go list -m -f '{{.Path}} {{.Version}}' all` in the build module. */
  selectedVersions?: string;
  graph?: string;
  /** Extra `dep` lines `go version -m` reports, keyed by the router version compiled into the binary. */
  extraDependencies?: Record<string, string[]>;
  testExitCode?: number;
}

export interface FakeSystem extends System {
  commands: string[];
  tests: (TestRequest & { binaryAtTestTime: string })[];
}

const ok = (stdout = ''): CommandOutcome => ({ exitCode: 0, stdout, stderr: '' });
const failed = (stderr: string): CommandOutcome => ({ exitCode: 1, stdout: '', stderr });

/** Stands in for git, Go and the user's test command, so no test needs the network or a Go toolchain. */
export const createFakeSystem = (options: FakeSystemOptions = {}): FakeSystem => {
  const routerTags = options.routerTags ?? { '0.299.0': commitA, '0.300.0': commitB };
  const commands: string[] = [];
  const tests: FakeSystem['tests'] = [];

  const goList = async (query: string): Promise<CommandOutcome> => {
    const [module, commit] = query.split('@');
    if (module === routerModule && Object.values(routerTags).includes(commit)) {
      const directory = await mkdtemp(path.join(tmpdir(), 'forge-gomod-'));
      const goMod = path.join(directory, 'go.mod');
      await writeFile(goMod, `module ${routerModule}\n\ngo 1.26.0\n`);
      return ok(
        JSON.stringify({
          Path: routerModule,
          Version: `v0.0.0-20260101000000-${commit.slice(0, 12)}`,
          GoMod: goMod,
          Origin: { Hash: commit },
        }),
      );
    }
    const known = options.modules?.[query];
    if (known) {
      return ok(JSON.stringify({ Path: known.Path, Version: known.Version, Origin: { Hash: known.Hash } }));
    }
    return failed(`go: ${query}: module not found`);
  };

  const run = async ({ file, args, cwd }: CommandRequest): Promise<CommandOutcome> => {
    commands.push([file, ...args].join(' '));

    if (file === 'git' && args[0] === 'ls-remote') {
      const [, url, ...patterns] = args;
      if (url !== 'https://github.com/wundergraph/cosmo') {
        const remote = options.remotes?.[url];
        return remote === undefined ? failed(`fatal: repository '${url}' not found`) : ok(remote);
      }
      const lines = Object.entries(routerTags).flatMap(([version, commit]) => [
        `${'f'.repeat(40)}\trefs/tags/router@${version}`,
        `${commit}\trefs/tags/router@${version}^{}`,
      ]);
      const wanted = lines.filter((line) =>
        patterns.some((pattern) => pattern.endsWith('*') || line.endsWith(`\t${pattern}`)),
      );
      return ok(wanted.join('\n'));
    }

    if (file === 'go' && args[0] === 'list' && args.includes('-json')) {
      return goList(args.at(-1) ?? '');
    }
    if (file === 'go' && args[0] === 'list') {
      return ok(options.selectedVersions ?? '');
    }
    if (file === 'go' && args.join(' ') === 'mod tidy') {
      return ok();
    }
    if (file === 'go' && args.join(' ') === 'mod graph') {
      return ok(options.graph ?? '');
    }
    if (file === 'go' && args[0] === 'build') {
      if (options.compileError !== undefined) {
        // A compiler that dies midway leaves a partial file at its output path.
        await writeFile(args[2], 'partial binary');
        return failed(options.compileError);
      }
      const goMod = await readFile(path.join(cwd ?? '', 'go.mod'), 'utf8');
      const routerVersion = new RegExp(`${routerModule} (\\S+)`).exec(goMod)?.[1];
      await writeFile(args[2], `router ${routerVersion}`);
      return ok();
    }
    if (file === 'go' && args[0] === 'version') {
      const routerVersion = (await readFile(args[2], 'utf8')).replace('router ', '');
      const dependencies = [
        `\tdep\t${routerModule}\t${routerVersion}\th1:x=`,
        ...(options.extraDependencies?.[routerVersion] ?? []),
      ];
      return ok([`${args[2]}: go1.26.0`, '\tpath\tforge.local/build', ...dependencies].join('\n'));
    }
    return failed(`unexpected command: ${file} ${args.join(' ')}`);
  };

  return {
    commands,
    tests,
    run,
    async runTest(request) {
      tests.push({ ...request, binaryAtTestTime: await readFile(request.env.FORGE_ROUTER_BINARY, 'utf8') });
      return { exitCode: options.testExitCode ?? 0 };
    },
  };
};

/** Creates a workspace directory holding the given files, keyed by relative path. */
export const createWorkspace = async (files: Record<string, string> = {}): Promise<string> => {
  const workspace = await realpath(await mkdtemp(path.join(tmpdir(), 'forge-workspace-')));
  for (const [relativePath, content] of Object.entries(files)) {
    await mkdir(path.dirname(path.join(workspace, relativePath)), { recursive: true });
    await writeFile(path.join(workspace, relativePath), content);
  }
  return workspace;
};

export const read = (workspace: string, relativePath: string): Promise<string> =>
  readFile(path.join(workspace, relativePath), 'utf8');

export interface ForgeRun {
  stdout: string;
  stderr: string;
  exitCode: number;
  /** The progress events of a JSON run, in order. */
  progress: { step: string; subject?: string; message: string }[];
}

/** Runs `wgc forge <args>` the way wgc does and captures what the caller would see. */
export const runForge = async (
  args: string[],
  {
    workspace,
    system = createFakeSystem(),
    caller = 'agent',
    prompts = createPrompts({ canPrompt: false }),
  }: { workspace: string; system?: System; caller?: CallerKind; prompts?: Prompts },
): Promise<ForgeRun> => {
  let stdout = '';
  let stderr = '';
  const context = createPluginContext({
    cliVersion: 'test',
    caller,
    endpoints: { cosmoApiUrl: '', cosmoWebUrl: '', hubUrl: '' },
    credentials: createCredentials({ env: {}, loginToken: () => Promise.resolve(undefined) }),
    prompts,
    stdout: { write: (chunk) => (stdout += chunk) },
    stderr: { write: (chunk) => (stderr += chunk) },
  });

  const program = new Command('wgc').exitOverride();
  createBuiltinEngine({ system, cwd: () => workspace }).register(program.command('forge'), context);

  process.exitCode = undefined;
  await program.parseAsync(['forge', ...args], { from: 'user' });
  const exitCode = Number(process.exitCode ?? 0);
  process.exitCode = undefined;

  const progress = stderr
    .split('\n')
    .filter((line) => line.startsWith('{"event":"progress"'))
    .map((line) => {
      const { event: _event, ...rest } = JSON.parse(line);
      return rest;
    });
  return { stdout, stderr, exitCode, progress };
};
