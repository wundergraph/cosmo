/* eslint-disable no-tabs -- the expected go.mod and main.go are indented with tabs, as gofmt writes them */
import { describe, expect, test } from 'vitest';
import {
  commitA,
  createFakeSystem,
  createWorkspace,
  lockForReleaseA,
  read,
  routerModule,
  runForge,
  versionA,
} from './harness.js';

const manifest = `version: 1
router:
  release: 0.299.0
binary: bin/router
modules:
  - path: ./modules/request-id
`;

const localModule = { 'modules/request-id/go.mod': 'module forge.local/request-id\n\ngo 1.26.0\n' };

describe('wgc forge build', () => {
  test('generates the build module, compiles, and reports the binary path', async () => {
    const workspace = await createWorkspace({ 'forge.yaml': manifest, ...localModule });
    const system = createFakeSystem();

    const run = await runForge(['build'], { workspace, system });

    expect(run.exitCode).toBe(0);
    expect(JSON.parse(run.stdout)).toEqual({
      status: 'success',
      binary: `${workspace}/bin/router`,
      router: { source: 'release 0.299.0', version: versionA, commit: commitA },
      modules: [],
      localModules: 1,
    });
    expect(await read(workspace, 'bin/router')).toBe(`router ${versionA}`);
    expect(await read(workspace, '.forge/build/go.mod')).toBe(`module forge.local/build

go 1.26.0

require (
	${routerModule} ${versionA}
	forge.local/request-id v0.0.0
)

replace forge.local/request-id => ../../modules/request-id
`);
    expect(await read(workspace, '.forge/build/main.go')).toBe(`// Code generated by wgc forge. DO NOT EDIT.

package main

import (
	routercmd "github.com/wundergraph/cosmo/router/cmd"

	_ "forge.local/request-id"
)

func main() {
	routercmd.Main()
}
`);
  });

  test('reports one progress event per real step, in order', async () => {
    const workspace = await createWorkspace({ 'forge.yaml': manifest, ...localModule });

    const run = await runForge(['build'], { workspace });

    expect(run.progress).toEqual([
      { step: 'resolve-router', subject: 'router release 0.299.0', message: 'Resolving the commit and Go version' },
      { step: 'resolve-router', subject: 'router release 0.299.0', message: `Resolved to ${versionA}` },
      {
        step: 'resolve-module',
        subject: './modules/request-id',
        message: 'Local module, built from disk and not pinned',
      },
      { step: 'write-build-module', subject: `${workspace}/.forge/build`, message: 'Writing go.mod and main.go' },
      { step: 'tidy', message: 'Resolving Go dependencies (go mod tidy)' },
      { step: 'compile', message: 'Compiling the router (go build)' },
      { step: 'place-binary', subject: `${workspace}/bin/router`, message: 'Moving the binary into place' },
    ]);
  });

  test('writes forge.lock on the first successful build and reuses it afterwards', async () => {
    const workspace = await createWorkspace({ 'forge.yaml': manifest, ...localModule });
    await runForge(['build'], { workspace });
    expect(await read(workspace, 'forge.lock')).toBe(lockForReleaseA);

    const system = createFakeSystem();
    const second = await runForge(['build'], { workspace, system });

    expect(second.progress[0]).toEqual({
      step: 'resolve-router',
      subject: 'router release 0.299.0',
      message: `Pinned at ${versionA}`,
    });
    expect(system.commands.filter((command) => command.startsWith('git ls-remote'))).toEqual([]);
  });

  test('a failed compile keeps the working binary and does not write pins', async () => {
    const workspace = await createWorkspace({
      'forge.yaml': manifest,
      ...localModule,
      'bin/router': 'the working router',
    });
    const system = createFakeSystem({ compileError: 'modules/request-id/module.go:12:2: undefined: nope' });

    const run = await runForge(['build'], { workspace, system });

    expect(run.exitCode).toBe(1);
    expect(JSON.parse(run.stdout)).toEqual({
      status: 'error',
      error: {
        message: 'The router did not compile:\nmodules/request-id/module.go:12:2: undefined: nope',
        input: `${workspace}/.forge/build`,
        fix: 'Fix the compile errors in the modules above. The existing binary was left in place.',
      },
    });
    expect(await read(workspace, 'bin/router')).toBe('the working router');
    await expect(read(workspace, 'forge.lock')).rejects.toThrow('ENOENT');
    expect(run.progress.map((event) => event.step)).not.toContain('place-binary');
  });

  test('a module that needs a newer router than the pinned one is a conflict naming it and both versions', async () => {
    const workspace = await createWorkspace({
      'forge.yaml': manifest,
      ...localModule,
      'bin/router': 'the working router',
    });
    const newer = 'v0.0.0-20260601000000-cccccccccccc';
    const system = createFakeSystem({
      selectedVersions: `forge.local/build \nforge.local/request-id v0.0.0\n${routerModule} ${newer}`,
      graph: [
        `forge.local/build ${routerModule}@${versionA}`,
        `forge.local/build forge.local/request-id@v0.0.0`,
        `forge.local/request-id@v0.0.0 ${routerModule}@${newer}`,
      ].join('\n'),
    });

    const run = await runForge(['build'], { workspace, system });

    expect(JSON.parse(run.stdout)).toEqual({
      status: 'error',
      error: {
        message: `Module dependency conflict: forge.local/request-id requires ${routerModule} ${newer}, but the workspace pins ${routerModule} ${versionA}.`,
        input: `forge.local/request-id requires ${routerModule} ${newer}`,
        fix: `Upgrade the router to a version that includes ${newer} with \`wgc forge router upgrade\`, or use a version of forge.local/request-id built for the pinned router.`,
      },
    });
    expect(await read(workspace, 'bin/router')).toBe('the working router');
    expect(system.commands.some((command) => command.startsWith('go build'))).toBe(false);
  });

  test('two entries that pin one module at different versions are a conflict before Go runs', async () => {
    const workspace = await createWorkspace({
      'forge.yaml': `version: 1
router:
  release: 0.299.0
modules:
  - go: github.com/acme/mod/headers
    version: v1.2.0
  - go: github.com/acme/mod/auth
    version: v1.3.0
`,
    });
    const system = createFakeSystem({
      modules: {
        'github.com/acme/mod@v1.2.0': { Path: 'github.com/acme/mod', Version: 'v1.2.0' },
        'github.com/acme/mod@v1.3.0': { Path: 'github.com/acme/mod', Version: 'v1.3.0' },
      },
    });

    const run = await runForge(['build'], { workspace, system });

    expect(JSON.parse(run.stdout).error).toEqual({
      message:
        'Module github.com/acme/mod is pinned at two versions, v1.2.0 and v1.3.0. A router is built with one version of each module.',
      input: 'forge.yaml: modules github.com/acme/mod',
      fix: 'Use the same version or ref for every entry of github.com/acme/mod in forge.yaml, then run `wgc forge lock`.',
    });
  });

  test('a local module directory without go.mod names the manifest entry', async () => {
    const workspace = await createWorkspace({ 'forge.yaml': manifest });

    const run = await runForge(['build'], { workspace });

    expect(JSON.parse(run.stdout).error).toEqual({
      message: 'Local module ./modules/request-id has no go.mod.',
      input: 'forge.yaml: modules path ./modules/request-id',
      fix: 'Create the module with `wgc forge create`, or run `go mod init` in ./modules/request-id.',
    });
  });

  test('without a workspace the failure says how to create one', async () => {
    const workspace = await createWorkspace();

    const run = await runForge(['build'], { workspace });

    expect(JSON.parse(run.stdout).error).toEqual({
      message: `No forge.yaml in ${workspace}.`,
      input: `${workspace}/forge.yaml`,
      fix: 'Run `wgc forge init` to create a Forge workspace here, or pass --dir <workspace>.',
    });
  });
});

describe('output for the caller', () => {
  test('a person at a terminal reads text: progress lines on stderr and a summary on stdout', async () => {
    const workspace = await createWorkspace({ 'forge.yaml': manifest, ...localModule });

    const run = await runForge(['build'], { workspace, caller: 'human' });

    expect(run.stdout).toBe(`Built ${workspace}/bin/router\n  router release 0.299.0 (${versionA}), 1 module(s)\n`);
    expect(run.stderr).toContain('Compiling the router (go build)');
    expect(run.stderr).not.toContain('{"event"');
  });

  test('--json gives a person the same JSON an agent gets', async () => {
    const workspace = await createWorkspace({ 'forge.yaml': manifest, ...localModule });

    const run = await runForge(['build', '--json'], { workspace, caller: 'human' });

    expect(JSON.parse(run.stdout)).toMatchObject({ status: 'success', binary: `${workspace}/bin/router` });
    expect(run.stderr.split('\n')[0]).toBe(
      '{"event":"progress","step":"resolve-router","subject":"router release 0.299.0","message":"Resolving the commit and Go version"}',
    );
  });

  test('a person reads a failure as text with its input and fix', async () => {
    const workspace = await createWorkspace();

    const run = await runForge(['build'], { workspace, caller: 'human' });

    expect(run.exitCode).toBe(1);
    expect(run.stdout).toBe('');
    expect(run.stderr).toContain(`No forge.yaml in ${workspace}.`);
    expect(run.stderr).toContain(`  input: ${workspace}/forge.yaml`);
    expect(run.stderr).toContain(
      '  fix: Run `wgc forge init` to create a Forge workspace here, or pass --dir <workspace>.',
    );
  });
});
