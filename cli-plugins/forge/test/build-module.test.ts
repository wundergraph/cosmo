/* eslint-disable no-tabs -- the expected go.mod and main.go are indented with tabs, as gofmt writes them */
import { expect, test } from 'vitest';
import { renderGoMod, renderMainGo } from '../src/build-module.js';
import type { BuildModule } from '../src/build-module.js';

const build: BuildModule = {
  goVersion: '1.26.0',
  routerVersion: 'v0.0.0-20260331121741-1a182a7bf4e6',
  remoteModules: [
    { module: 'github.com/acme/mod', package: 'github.com/acme/mod/headers', version: 'v1.2.0' },
    { module: 'github.com/acme/mod', package: 'github.com/acme/mod/auth', version: 'v1.2.0' },
  ],
  localModules: [{ module: 'forge.local/request-id', directory: '../../modules/request-id' }],
};

test('go.mod requires the pinned router and modules and replaces local modules with their directory', () => {
  expect(renderGoMod(build)).toBe(`module forge.local/build

go 1.26.0

require (
	github.com/wundergraph/cosmo/router v0.0.0-20260331121741-1a182a7bf4e6
	github.com/acme/mod v1.2.0
	forge.local/request-id v0.0.0
)

replace forge.local/request-id => ../../modules/request-id
`);
});

test('main.go imports the router command and every module package for its side effects', () => {
  expect(renderMainGo(build)).toBe(`// Code generated by wgc forge. DO NOT EDIT.

package main

import (
	routercmd "github.com/wundergraph/cosmo/router/cmd"

	_ "github.com/acme/mod/headers"
	_ "github.com/acme/mod/auth"
	_ "forge.local/request-id"
)

func main() {
	routercmd.Main()
}
`);
});

test('a workspace without modules builds the plain router', () => {
  const plain: BuildModule = { ...build, remoteModules: [], localModules: [] };

  expect(renderGoMod(plain)).toBe(`module forge.local/build

go 1.26.0

require (
	github.com/wundergraph/cosmo/router v0.0.0-20260331121741-1a182a7bf4e6
)
`);
  expect(renderMainGo(plain)).toBe(`// Code generated by wgc forge. DO NOT EDIT.

package main

import (
	routercmd "github.com/wundergraph/cosmo/router/cmd"
)

func main() {
	routercmd.Main()
}
`);
});

test('a router checkout replaces the pinned router for router development', () => {
  expect(renderGoMod({ ...build, remoteModules: [], localModules: [], routerReplace: '/src/cosmo/router' }))
    .toBe(`module forge.local/build

go 1.26.0

require (
	github.com/wundergraph/cosmo/router v0.0.0-20260331121741-1a182a7bf4e6
)

replace github.com/wundergraph/cosmo/router => /src/cosmo/router
`);
});
